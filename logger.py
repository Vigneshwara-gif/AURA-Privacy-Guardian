# ============================================================
# SAFE NUMERIC CONVERSION
# ============================================================

def _safe_float(
    value: Any,
    default: float = 0.0,
) -> float:
    """
    Convert a value to float safely.
    """

    try:

        number = float(value)

        if pd.isna(number):
            return default

        return number

    except (
        TypeError,
        ValueError,
    ):

        return default


def _safe_int(
    value: Any,
    default: int = 0,
) -> int:
    """
    Convert a value to integer safely.
    """

    try:

        number = int(
            float(value)
        )

        return number

    except (
        TypeError,
        ValueError,
    ):

        return default


def _safe_text(
    value: Any,
    default: str = "",
) -> str:
    """
    Convert a value to a clean string.
    """

    if value is None:
        return default

    try:

        if pd.isna(value):
            return default

    except (TypeError, ValueError):
        pass

    return str(
        value
    )


# ============================================================
# EVENT ID
# ============================================================

def _generate_event_id() -> str:
    """
    Generate a human-readable event identifier.
    """

    timestamp = pd.Timestamp.now()

    return timestamp.strftime(
        "AURA-%Y%m%d-%H%M%S-%f"
    )[:-3]


# ============================================================
# BASELINE STORAGE
# ============================================================

def save_baseline(
    data,
    filename: Optional[str] = None,
) -> Path:
    """
    Save the ML baseline.

    Expected columns:

        CPU
        Net
        Cam
    """

    _ensure_data_dir()

    path = (
        Path(filename)
        if filename
        else BASELINE_FILE
    )

    rows = list(
        data
    )

    dataframe = pd.DataFrame(
        rows,
        columns=BASELINE_COLUMNS,
    )

    # Numeric validation.
    for column in BASELINE_COLUMNS:

        dataframe[column] = pd.to_numeric(
            dataframe[column],
            errors="coerce",
        )

    dataframe = dataframe.dropna(
        subset=BASELINE_COLUMNS
    )

    if dataframe.empty:

        raise ValueError(
            "Cannot save an empty AURA baseline."
        )

    dataframe.to_csv(
        path,
        index=False,
    )

    return path


# ============================================================
# BASELINE LOADING
# ============================================================

def load_baseline(
    filename: Optional[str] = None,
) -> pd.DataFrame:
    """
    Load the AURA ML baseline.

    Returns an empty DataFrame when no baseline exists.
    """

    path = (
        Path(filename)
        if filename
        else BASELINE_FILE
    )

    if not path.exists():

        return pd.DataFrame(
            columns=BASELINE_COLUMNS
        )

    try:

        dataframe = pd.read_csv(
            path
        )

    except (
        OSError,
        pd.errors.EmptyDataError,
        pd.errors.ParserError,
    ):

        return pd.DataFrame(
            columns=BASELINE_COLUMNS
        )

    # Make sure all required columns exist.
    for column in BASELINE_COLUMNS:

        if column not in dataframe.columns:

            dataframe[column] = (
                DEFAULTS[column]
            )

    dataframe = dataframe[
        BASELINE_COLUMNS
    ]

    # Convert everything to numeric.
    for column in BASELINE_COLUMNS:

        dataframe[column] = pd.to_numeric(
            dataframe[column],
            errors="coerce",
        )

    dataframe = dataframe.dropna()

    return dataframe.reset_index(
        drop=True
    )


# ============================================================
# LOG ROW NORMALIZATION
# ============================================================

def _normalize_log_row(
    values: dict[str, Any],
) -> dict[str, Any]:
    """
    Create a complete AURA log row.

    Missing fields receive safe defaults.

    This is what allows old code and new code to coexist.
    """

    row = dict(
        DEFAULTS
    )

    row.update(
        values
    )

    # --------------------------------------------------------
    # Numeric fields
    # --------------------------------------------------------

    float_fields = {

        "CPU",
        "Net",

        "Memory",
        "Disk",

        "Disk_Read",
        "Disk_Write",

        "CPU_Frequency",

        "Network_Download",
        "Network_Upload",

        "IF_Score",
        "LOF_Score",

        "IF_Anomaly_Intensity",
        "LOF_Anomaly_Intensity",

        "Anomaly_Confidence",

        "Strongest_Feature_Deviation",

    }

    int_fields = {

        "Cam",

        "Process_Count",

        "Remote_Connections",
        "Established_Connections",
        "Listening_Connections",

        "Sensitive_Files",

        "IF_Anomaly",
        "LOF_Anomaly",
        "Anomaly",

        "Risk_Score",

        "Privacy_Event",

        "Potential_Data_Exfiltration",
        "Potential_Camera_Risk",

        "Behavioral_Adjustment",

        "Training_Samples",

    }

    for field in float_fields:

        row[field] = _safe_float(
            row[field]
        )

    for field in int_fields:

        row[field] = _safe_int(
            row[field]
        )

    # --------------------------------------------------------
    # Text fields
    # --------------------------------------------------------

    text_fields = {

        "Timestamp",
        "Event_ID",

        "Strongest_Feature",

        "Risk",
        "Severity",

        "Network_Level",
        "Process_Level",

        "Model_Health",

    }

    for field in text_fields:

        row[field] = _safe_text(
            row[field],
            DEFAULTS[field],
        )

    return row


# ============================================================
# LEGACY LOG MIGRATION
# ============================================================

def _migrate_logs(
    path: Path,
) -> pd.DataFrame:
    """
    Read an existing AURA CSV and upgrade it to the current
    schema.

    Existing historical data is preserved.

    New fields receive safe defaults.
    """

    if not path.exists():

        return pd.DataFrame(
            columns=COLUMNS
        )

    try:

        dataframe = pd.read_csv(
            path
        )

    except (
        OSError,
        pd.errors.EmptyDataError,
        pd.errors.ParserError,
    ):

        return pd.DataFrame(
            columns=COLUMNS
        )

    # --------------------------------------------------------
    # Add missing columns
    # --------------------------------------------------------

    for column in COLUMNS:

        if column not in dataframe.columns:

            dataframe[column] = (
                DEFAULTS[column]
            )

    # --------------------------------------------------------
    # Remove unknown columns from the persistent schema.
    #
    # This prevents old experimental fields from breaking
    # future versions of AURA.
    # --------------------------------------------------------

    dataframe = dataframe[
        COLUMNS
    ]

    # --------------------------------------------------------
    # Normalize historical values
    # --------------------------------------------------------

    for column in COLUMNS:

        if column in {
            "Timestamp",
            "Event_ID",
            "Risk",
            "Severity",
            "Network_Level",
            "Process_Level",
            "Strongest_Feature",
            "Model_Health",
        }:

            continue

        if column in {
            "Cam",
            "Process_Count",
            "Remote_Connections",
            "Established_Connections",
            "Listening_Connections",
            "Sensitive_Files",
            "IF_Anomaly",
            "LOF_Anomaly",
            "Anomaly",
            "Risk_Score",
            "Privacy_Event",
            "Potential_Data_Exfiltration",
            "Potential_Camera_Risk",
            "Behavioral_Adjustment",
            "Training_Samples",
        }:

            dataframe[column] = pd.to_numeric(
                dataframe[column],
                errors="coerce",
            ).fillna(
                DEFAULTS[column]
            ).astype(int)

        else:

            dataframe[column] = pd.to_numeric(
                dataframe[column],
                errors="coerce",
            ).fillna(
                DEFAULTS[column]
            )

    return dataframe


