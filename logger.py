# APPEND SECURITY EVENT
# ============================================================

def append_log(
    cpu: float,
    net: float,
    cam: int,

    if_anomaly: int = 0,
    lof_anomaly: int = 0,
    anomaly: int = 0,

    risk: str = "NORMAL",

    process_count: int = 0,
    remote_connections: int = 0,
    sensitive_files: int = 0,

    risk_score: int = 0,
    network_level: str = "NORMAL",

    privacy_event: int = 0,
    potential_data_exfiltration: int = 0,

    filename: Optional[str] = None,

    # --------------------------------------------------------
    # Extended telemetry
    # --------------------------------------------------------

    memory: float = 0.0,
    disk: float = 0.0,

    disk_read: float = 0.0,
    disk_write: float = 0.0,

    cpu_frequency: float = 0.0,

    network_download: float = 0.0,
    network_upload: float = 0.0,

    established_connections: int = 0,
    listening_connections: int = 0,

    # --------------------------------------------------------
    # AI intelligence
    # --------------------------------------------------------

    if_score: float = 0.0,
    lof_score: float = 0.0,

    if_anomaly_intensity: float = 0.0,
    lof_anomaly_intensity: float = 0.0,

    anomaly_confidence: float = 0.0,

    strongest_feature: str = "",
    strongest_feature_deviation: float = 0.0,

    # --------------------------------------------------------
    # Risk intelligence
    # --------------------------------------------------------

    severity: str = "INFO",

    process_level: str = "NORMAL",

    potential_camera_risk: int = 0,

    behavioral_adjustment: int = 0,

    # --------------------------------------------------------
    # Model information
    # --------------------------------------------------------

    model_health: str = "UNKNOWN",

    training_samples: int = 0,

) -> Path:
    """
    Append one complete AURA security event.

    The function remains backward-compatible with the original
    AURA append_log() interface.
    """

    _ensure_data_dir()

    path = (
        Path(filename)
        if filename
        else LOG_FILE
    )

    # --------------------------------------------------------
    # Build row
    # --------------------------------------------------------

    row = _normalize_log_row({

        "Timestamp": pd.Timestamp.now().strftime(
            "%Y-%m-%d %H:%M:%S"
        ),

        "Event_ID": _generate_event_id(),

        "CPU": cpu,
        "Net": net,
        "Cam": cam,

        "Memory": memory,
        "Disk": disk,

        "Disk_Read": disk_read,
        "Disk_Write": disk_write,

        "CPU_Frequency": cpu_frequency,

        "Network_Download": network_download,
        "Network_Upload": network_upload,

        "Process_Count": process_count,

        "Remote_Connections": remote_connections,
        "Established_Connections": (
            established_connections
        ),
        "Listening_Connections": (
            listening_connections
        ),

        "Sensitive_Files": sensitive_files,

        "IF_Anomaly": if_anomaly,
        "LOF_Anomaly": lof_anomaly,
        "Anomaly": anomaly,

        "IF_Score": if_score,
        "LOF_Score": lof_score,

        "IF_Anomaly_Intensity": (
            if_anomaly_intensity
        ),
        "LOF_Anomaly_Intensity": (
            lof_anomaly_intensity
        ),

        "Anomaly_Confidence": (
            anomaly_confidence
        ),

        "Strongest_Feature": (
            strongest_feature
        ),

        "Strongest_Feature_Deviation": (
            strongest_feature_deviation
        ),

        "Risk": risk,

        "Severity": severity,

        "Risk_Score": risk_score,

        "Network_Level": network_level,

        "Process_Level": process_level,

        "Privacy_Event": privacy_event,

        "Potential_Data_Exfiltration": (
            potential_data_exfiltration
        ),

        "Potential_Camera_Risk": (
            potential_camera_risk
        ),

        "Behavioral_Adjustment": (
            behavioral_adjustment
        ),

        "Model_Health": model_health,

        "Training_Samples": training_samples,
    })

    # --------------------------------------------------------
    # Handle existing logs
    # --------------------------------------------------------

    if path.exists():

        existing = _migrate_logs(
            path
        )

        new_row = pd.DataFrame(
            [row],
            columns=COLUMNS,
        )

        combined = pd.concat(
            [
                existing,
                new_row,
            ],
            ignore_index=True,
        )

        combined.to_csv(
            path,
            index=False,
        )

    else:

        dataframe = pd.DataFrame(
            [row],
            columns=COLUMNS,
        )

        dataframe.to_csv(
            path,
            index=False,
        )

    # --------------------------------------------------------
    # Also record in modern SQLite storage engine
    # --------------------------------------------------------
    try:
        from aura.core.paths import get_paths
        from aura.models.types import PrivacyHardwareStatus, SecurityEvent, TelemetrySnapshot
        from aura.storage.sqlite import StorageEngine

        db_path = get_paths().database_path
        storage = StorageEngine(db_path)

        t_snap = TelemetrySnapshot(
            timestamp=row["Timestamp"],
            cpu_percent=float(row["CPU"]),
            memory_percent=float(row["Memory"]),
            disk_percent=float(row["Disk"]),
            disk_io_write_kbps=float(row["Disk_Write"]),
            net_upload_kbps=float(row["Net_Upload"]),
            net_download_kbps=float(row["Network_Download"]),
            process_count=int(row["Process_Count"]),
            established_connections=int(row["Established_Connections"]),
            listening_connections=int(row["Listening_Connections"]),
            remote_connections=int(row["Remote_Connections"]),
            camera_status=PrivacyHardwareStatus.AVAILABLE if int(row["Cam"]) else PrivacyHardwareStatus.NOT_DETECTED,
        )
        storage.record_telemetry(t_snap)

        sec_evt = SecurityEvent(
            event_id=row["Event_ID"],
            timestamp=row["Timestamp"],
            event_type="SCAN_EVENT",
            severity=row["Severity"],
            risk_score=float(row["Risk_Score"]),
            source="logger.append_log",
            summary=f"Scan record: {row['Severity']} (Risk Score: {row['Risk_Score']})",
        )
        storage.record_security_event(sec_evt)
    except Exception:
        pass

    return path


# ============================================================
# LOAD SECURITY LOGS
# ============================================================

def load_logs(
    filename: Optional[str] = None,
) -> pd.DataFrame:
    """
    Load AURA security logs using the current schema.

    Older logs are automatically upgraded in memory.
    """

    path = (
        Path(filename)
        if filename
        else LOG_FILE
    )

    if not path.exists():

        return pd.DataFrame(
            columns=COLUMNS
        )

    dataframe = _migrate_logs(
        path
    )

    # --------------------------------------------------------
    # Timestamp conversion
    # --------------------------------------------------------

    if "Timestamp" in dataframe.columns:

        dataframe["Timestamp"] = pd.to_datetime(
            dataframe["Timestamp"],
            errors="coerce",
        )

    return dataframe.reset_index(
        drop=True
    )


