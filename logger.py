# ============================================================
# LOG STATISTICS
# ============================================================

def get_log_statistics(
    filename: Optional[str] = None,
) -> dict[str, Any]:
    """
    Generate a compact summary of AURA's historical events.

    Useful for the future Analytics dashboard.
    """

    logs = load_logs(
        filename
    )

    if logs.empty:

        return {
            "total_events": 0,
            "anomalies": 0,
            "privacy_events": 0,
            "high_risk_events": 0,
            "critical_events": 0,
            "average_risk_score": 0.0,
            "maximum_risk_score": 0,
        }

    risk_scores = pd.to_numeric(
        logs["Risk_Score"],
        errors="coerce",
    ).fillna(0)

    risks = (
        logs["Risk"]
        .astype(str)
        .str.upper()
    )

    anomalies = pd.to_numeric(
        logs["Anomaly"],
        errors="coerce",
    ).fillna(0)

    privacy_events = pd.to_numeric(
        logs["Privacy_Event"],
        errors="coerce",
    ).fillna(0)

    return {
        "total_events": int(
            len(logs)
        ),

        "anomalies": int(
            anomalies.sum()
        ),

        "privacy_events": int(
            privacy_events.sum()
        ),

        "high_risk_events": int(
            risks.isin(
                [
                    "HIGH",
                    "CRITICAL",
                ]
            ).sum()
        ),

        "critical_events": int(
            (
                risks == "CRITICAL"
            ).sum()
        ),

        "average_risk_score": round(
            float(
                risk_scores.mean()
            ),
            2,
        ),

        "maximum_risk_score": int(
            risk_scores.max()
        ),
    }


